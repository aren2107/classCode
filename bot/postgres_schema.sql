CREATE TABLE IF NOT EXISTS users (
                        user_id BIGINT PRIMARY KEY,
                        username TEXT NOT NULL,
                        xp BIGINT DEFAULT 0,
                        level BIGINT DEFAULT 1,
                        streak_count BIGINT DEFAULT 0,
                        last_active_date TEXT DEFAULT '',
                        joined_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                    );

                    CREATE TABLE IF NOT EXISTS user_progress (
                        user_id BIGINT,
                        language TEXT NOT NULL,
                        topic_id TEXT NOT NULL,
                        status TEXT DEFAULT 'locked',
                        completed_at TIMESTAMP,
                        PRIMARY KEY (user_id, language, topic_id)
                    );

                    CREATE TABLE IF NOT EXISTS quiz_attempts (
                        attempt_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        user_id BIGINT,
                        topic_id TEXT NOT NULL,
                        language TEXT NOT NULL,
                        difficulty TEXT NOT NULL,
                        score BIGINT NOT NULL,
                        total BIGINT DEFAULT 1,
                        passed BIGINT NOT NULL,
                        attempted_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                    );

                    CREATE TABLE IF NOT EXISTS practice_quiz_xp_rewards (
                        user_id BIGINT NOT NULL,
                        language TEXT NOT NULL,
                        topic_id TEXT NOT NULL,
                        xp_awarded BIGINT NOT NULL,
                        recorded_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                        PRIMARY KEY (user_id, language, topic_id)
                    );

                    CREATE TABLE IF NOT EXISTS user_badges (
                        user_id BIGINT,
                        badge_id TEXT NOT NULL,
                        unlocked_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                        PRIMARY KEY (user_id, badge_id)
                    );

                    CREATE TABLE IF NOT EXISTS daily_challenges (
                        challenge_id TEXT PRIMARY KEY,
                        language TEXT NOT NULL,
                        title TEXT NOT NULL,
                        description TEXT NOT NULL,
                        requirements TEXT NOT NULL,
                        test_cases TEXT NOT NULL,
                        created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                        active_date TEXT UNIQUE
                    );

                    CREATE TABLE IF NOT EXISTS daily_submissions (
                        submission_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        user_id BIGINT,
                        challenge_id TEXT NOT NULL,
                        language TEXT NOT NULL,
                        status TEXT NOT NULL,
                        score BIGINT DEFAULT 0,
                        submitted_at TIMESTAMP WITHOUT TIME ZONE DEFAULT timezone('Asia/Manila', CURRENT_TIMESTAMP),
                        UNIQUE(user_id, challenge_id)
                    );

                    CREATE TABLE IF NOT EXISTS xp_history (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        user_id BIGINT NOT NULL,
                        amount BIGINT NOT NULL,
                        reason TEXT NOT NULL,
                        created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                    );

                    CREATE TABLE IF NOT EXISTS daily_goals (
                        user_id BIGINT NOT NULL,
                        goal_date TEXT NOT NULL,
                        lessons BIGINT DEFAULT 0,
                        quizzes BIGINT DEFAULT 0,
                        challenges BIGINT DEFAULT 0,
                        xp_earned BIGINT DEFAULT 0,
                        PRIMARY KEY(user_id, goal_date)
                    );

                    CREATE TABLE IF NOT EXISTS projects (
                        project_id TEXT PRIMARY KEY,
                        title TEXT NOT NULL,
                        language TEXT NOT NULL,
                        difficulty TEXT NOT NULL,
                        description TEXT NOT NULL,
                        requirements TEXT NOT NULL,
                        xp BIGINT DEFAULT 150
                    );

                    CREATE TABLE IF NOT EXISTS project_progress (
                        user_id BIGINT NOT NULL,
                        project_id TEXT NOT NULL,
                        status TEXT DEFAULT 'available',
                        completed_at TIMESTAMP,
                        PRIMARY KEY(user_id, project_id)
                    );

                    CREATE TABLE IF NOT EXISTS classes (
                        class_id TEXT PRIMARY KEY,
                        name TEXT NOT NULL,
                        teacher_id BIGINT NOT NULL,
                        created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                    );

                    CREATE TABLE IF NOT EXISTS class_members (
                        class_id TEXT NOT NULL,
                        user_id BIGINT NOT NULL,
                        role TEXT DEFAULT 'student',
                        joined_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                        PRIMARY KEY(class_id, user_id)
                    );

                    CREATE TABLE IF NOT EXISTS assignments (
                        assignment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        class_id TEXT NOT NULL,
                        title TEXT NOT NULL,
                        language TEXT NOT NULL,
                        topic_id TEXT,
                        due_date TEXT,
                        created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                    );

                    CREATE TABLE IF NOT EXISTS assignment_submissions (
                        assignment_id BIGINT NOT NULL,
                        user_id BIGINT NOT NULL,
                        status TEXT DEFAULT 'submitted',
                        submitted_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                        PRIMARY KEY(assignment_id, user_id)
                    );

                    CREATE TABLE IF NOT EXISTS code_snippets (
                        snippet_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        user_id BIGINT NOT NULL,
                        title TEXT NOT NULL,
                        language TEXT NOT NULL,
                        code TEXT NOT NULL,
                        note TEXT DEFAULT '',
                        created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                    );

                    CREATE TABLE IF NOT EXISTS personal_notes (
                        note_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        user_id BIGINT NOT NULL,
                        title TEXT NOT NULL,
                        body TEXT NOT NULL,
                        created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                        updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                    );

                    CREATE TABLE IF NOT EXISTS user_titles (
                        user_id BIGINT NOT NULL,
                        title_id TEXT NOT NULL,
                        unlocked_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                        PRIMARY KEY(user_id, title_id)
                    );

                    CREATE TABLE IF NOT EXISTS user_stats (
                        user_id BIGINT PRIMARY KEY,
                        coding_runs BIGINT DEFAULT 0,
                        bugs_fixed BIGINT DEFAULT 0,
                        problems_solved BIGINT DEFAULT 0,
                        projects_completed BIGINT DEFAULT 0,
                        study_minutes BIGINT DEFAULT 0
                    );

                    CREATE TABLE IF NOT EXISTS daily_missions (
                        mission_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        user_id BIGINT NOT NULL,
                        mission_date TEXT NOT NULL,
                        kind TEXT NOT NULL,
                        target BIGINT NOT NULL,
                        progress BIGINT DEFAULT 0,
                        reward BIGINT DEFAULT 0,
                        UNIQUE(user_id, mission_date, kind)
                    );

                    CREATE TABLE IF NOT EXISTS bug_puzzles (
                        puzzle_id TEXT PRIMARY KEY,
                        language TEXT NOT NULL,
                        title TEXT NOT NULL,
                        code TEXT NOT NULL,
                        answer TEXT NOT NULL,
                        explanation TEXT NOT NULL,
                        difficulty TEXT DEFAULT 'Beginner'
                    );

                    CREATE TABLE IF NOT EXISTS bug_attempts (
                        user_id BIGINT NOT NULL,
                        puzzle_id TEXT NOT NULL,
                        solved BIGINT DEFAULT 0,
                        attempts BIGINT DEFAULT 0,
                        PRIMARY KEY(user_id, puzzle_id)
                    );

                    CREATE TABLE IF NOT EXISTS study_groups (
                        group_id TEXT PRIMARY KEY,
                        name TEXT NOT NULL,
                        owner_id BIGINT NOT NULL,
                        topic TEXT NOT NULL,
                        created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                    );

                    CREATE TABLE IF NOT EXISTS study_group_members (
                        group_id TEXT NOT NULL,
                        user_id BIGINT NOT NULL,
                        role TEXT DEFAULT 'member',
                        joined_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                        PRIMARY KEY(group_id, user_id)
                    );

                    CREATE TABLE IF NOT EXISTS pair_queue (
                        user_id BIGINT PRIMARY KEY,
                        language TEXT NOT NULL,
                        joined_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                    );

                    CREATE TABLE IF NOT EXISTS event_progress (
                        user_id BIGINT NOT NULL,
                        event_id TEXT NOT NULL,
                        points BIGINT DEFAULT 0,
                        PRIMARY KEY(user_id, event_id)
                    );

                    CREATE TABLE IF NOT EXISTS portfolio_projects (
                        portfolio_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        user_id BIGINT NOT NULL,
                        project_id TEXT NOT NULL,
                        description TEXT DEFAULT '',
                        url TEXT DEFAULT '',
                        featured BIGINT DEFAULT 0,
                        created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                    );

                    CREATE TABLE IF NOT EXISTS certificates (
                        certificate_id TEXT PRIMARY KEY,
                        user_id BIGINT NOT NULL,
                        language TEXT NOT NULL,
                        issued_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                    );

                    CREATE TABLE IF NOT EXISTS practical_exams (
                        exam_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        title TEXT NOT NULL,
                        language TEXT NOT NULL,
                        difficulty TEXT NOT NULL,
                        problem TEXT NOT NULL,
                        topic TEXT DEFAULT '',
                        test_cases TEXT NOT NULL DEFAULT '[]',
                        allowed_concepts TEXT DEFAULT '',
                        starter_code TEXT DEFAULT '',
                        created_by BIGINT NOT NULL,
                        forum_channel_id BIGINT,
                        thread_id BIGINT,
                        active BIGINT DEFAULT 1,
                        created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                    );

                    CREATE TABLE IF NOT EXISTS practical_exam_submissions (
                        submission_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        exam_id BIGINT NOT NULL,
                        user_id BIGINT NOT NULL,
                        thread_id BIGINT NOT NULL,
                        code TEXT NOT NULL,
                        score BIGINT NOT NULL DEFAULT 0,
                        passed_tests BIGINT NOT NULL DEFAULT 0,
                        total_tests BIGINT NOT NULL DEFAULT 0,
                        status TEXT NOT NULL,
                        feedback TEXT DEFAULT '',
                        submitted_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                    );
                    CREATE TABLE IF NOT EXISTS attendance_records (
                        user_id BIGINT NOT NULL,
                        attendance_date TEXT NOT NULL,
                        checked_in_at TEXT NOT NULL,
                        PRIMARY KEY (user_id, attendance_date)
                    );


CREATE TABLE IF NOT EXISTS lesson_mastery (
    user_id BIGINT NOT NULL,
    language TEXT NOT NULL,
    topic_id TEXT NOT NULL,
    best_score BIGINT DEFAULT 0,
    last_score BIGINT DEFAULT 0,
    attempts BIGINT DEFAULT 0,
    passed BIGINT DEFAULT 0,
    xp_awarded BIGINT DEFAULT 0,
    weak_categories TEXT DEFAULT '',
    review_due_at TIMESTAMP,
    demonstration_completed BIGINT DEFAULT 0,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY(user_id, language, topic_id)
);
